"""Write docs/extraction-review.md: model pillars next to seed tags, plus every warning, for human review (task T4).

Usage: python -m si.extraction_report
"""

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
EXTRACTED = ROOT / "data" / "processed" / "extracted.json"
SEED = ROOT / "data" / "domain" / "seed_pillars.json"
REPORT = ROOT / "docs" / "extraction-review.md"


def compare(model_pillars, seed_pillars):
    model, seed = set(model_pillars), set(seed_pillars)
    if model == seed:
        return "agree"
    if not seed:
        return "seed has no pillar"
    if model & seed:
        return "partial"
    return "disagree"


def build_rows(extracted, seed):
    seed_by_accession = {s["accession"]: s for s in seed["investigations"]}
    rows = []
    for record in extracted:
        seed_entry = seed_by_accession.get(record["accession"], {})
        rows.append({
            "accession": record["accession"],
            "name": record.get("acronym") or seed_entry.get("acronym") or "",
            "model": record.get("pillars") or [],
            "seed": seed_entry.get("pillars") or [],
            "seed_note": seed_entry.get("role") or seed_entry.get("note") or "",
            "status": compare(record.get("pillars") or [], seed_entry.get("pillars") or []),
            "warnings": record.get("warnings") or [],
        })
    return rows


def render(rows, prompt_version, model):
    counts = {}
    for row in rows:
        counts[row["status"]] = counts.get(row["status"], 0) + 1
    order = ["agree", "partial", "disagree", "seed has no pillar"]
    lines = [
        "# Extraction review",
        "",
        f"Generated by `python -m si.extraction_report` from `data/processed/extracted.json` (prompt {prompt_version}, model {model}).",
        "",
        "Model pillars are suggestions. The final pillars come from the hand-checked domain tags (task T1). "
        "Use this page for task T4: check every row that is not `agree` and every warning.",
        "",
        "| Status | Count |",
        "|---|---|",
        *[f"| {status} | {counts.get(status, 0)} |" for status in order],
        "",
        "| Accession | Investigation | Model pillars | Seed pillars | Status | Warnings |",
        "|---|---|---|---|---|---|",
    ]
    for row in rows:
        seed = ", ".join(row["seed"]) or f"none ({row['seed_note']})"
        lines.append(f"| {row['accession']} | {row['name']} | {', '.join(row['model']) or 'none'} | {seed} | "
                     f"{row['status']} | {'<br>'.join(row['warnings'])} |")
    return "\n".join(lines) + "\n"


def main():
    extracted = json.loads(EXTRACTED.read_text(encoding="utf-8"))
    seed = json.loads(SEED.read_text(encoding="utf-8"))
    rows = build_rows(extracted, seed)
    first = extracted[0] if extracted else {}
    REPORT.write_text(render(rows, first.get("prompt_version"), first.get("model")), encoding="utf-8", newline="\n")
    print(f"wrote {REPORT.relative_to(ROOT)}: " + ", ".join(f"{s} {sum(r['status'] == s for r in rows)}"
                                                       for s in ("agree", "partial", "disagree", "seed has no pillar")))


if __name__ == "__main__":
    main()
